namespace pp::game
{

void Player::reset()
{
    x_f = 0.f;
    y_f = 0.f;
    x_previousDraw = 0;
    y_previousDraw = 0;
    animationIndex = 0;
    moveLeft = false;
    moveRight = false;
    x_f = 10.f;
    y_f = 10.f;
}

void Game::init(Display& _display)
{
    m_displayRef = &_display;
    m_player.reset();
}

void Game::deinit()
{
}

void Game::dispatch(const AppEvent& _event)
{
    switch (_event.type)
    {
    case AppEvent::Type::ButtonPressed:
    {
        if (_event.button == ButtonName::LEFT)
        {
            m_player.moveLeft = true;
            m_player.animationIndex = 4;
        }
        else if (_event.button == ButtonName::RIGHT)
        {
            m_player.moveRight = true;
            m_player.animationIndex = 1;
        }
        break;
    }
    case AppEvent::Type::ButtonReleased:
    {
        if (_event.button == ButtonName::LEFT)
            m_player.moveLeft = false;
        else if (_event.button == ButtonName::RIGHT)
            m_player.moveRight = false;

        break;
    }
    case AppEvent::Type::Tick:
    {
        int previousAnimationIndex = m_player.animationIndex;
        if (m_player.moveLeft || m_player.moveRight)
        {
            int d = m_player.moveLeft ? -1 : 1;
            m_player.x_f += d * TICK_DT_S * m_player.x_speed;
            ++m_player.animationIndex;
            if (m_player.animationIndex == 4)
                m_player.animationIndex = 1;
            else if (m_player.animationIndex == 7)
                m_player.animationIndex = 4;
        }
        else
        {
            m_player.animationIndex = 0;
        }

        int x_draw = (int)m_player.x_f;
        int y_draw = (int)m_player.y_f;
        if (m_player.x_previousDraw != x_draw || m_player.y_previousDraw != y_draw ||
            previousAnimationIndex != m_player.animationIndex)
        {   
            m_displayRef->drawBitmap(x_draw, y_draw, playerBitmaps[m_player.animationIndex], PLAYER_BITMAP_WIDTH, PLAYER_BITMAP_HEIGHT);
        }
        m_player.x_previousDraw = x_draw;
        m_player.y_previousDraw = y_draw;

        break;
    }
    default:
        break;
    }
}

} // namespace pp::game
